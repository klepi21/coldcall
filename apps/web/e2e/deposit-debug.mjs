import { chromium } from '@playwright/test';
const BASE = process.env.BASE || 'https://45-81-6-214.sslip.io';
const OUT = '/private/tmp/claude-501/-Users-konstantinoslepidas/f20ec7f5-ba28-4ba1-a433-882b71ac4224/scratchpad';
