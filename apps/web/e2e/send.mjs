// Sign up, get test USDC, send 5 USDC to a fresh address, check the recipient got it.
import { chromium } from '@playwright/test';
import nacl from 'tweetnacl';
import bs58 from 'bs58';
const BASE = process.env.BASE || 'http://localhost:3000';
const OUT = process.argv[2] ?? '/tmp';
const b = await chromium.launch({ executablePath: `${process.env.HOME}/Library/Caches/ms-playwright/chromium_headless_shell-1234/chrome-headless-shell-mac-arm64/chrome-headless-shell` });
const page = await (await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })).newPage();
page.on('pageerror', (e) => console.log('PAGEERR', e.message));
await page.goto(BASE + '/', { waitUntil: 'load' });
await page.getByRole('button', { name: /play free now/i }).click();
await page.getByRole('button', { name: /create my account/i }).click();
await page.getByRole('button', { name: /^skip$/i }).click();
await page.getByLabel(/your player name/i).fill('Sender');
await page.getByLabel(/18 or older/i).check();
await page.getByRole('checkbox').nth(1).check();
await page.getByRole('button', { name: /start my free practice game/i }).click();
await page.waitForURL(/\/play/);
await page.goto(BASE + '/wallet', { waitUntil: 'load' });
await page.getByRole('button', { name: /get 100 test usdc/i }).click();
await page.getByText(/100 test USDC are in your wallet/i).waitFor({ timeout: 60000 });
const to = bs58.encode(nacl.sign.keyPair().publicKey);
await page.getByRole('button', { name: /^send usdc$/i }).first().waitFor(); await page.waitForTimeout(1500); await page.screenshot({ path: OUT + '/portfolio.png', fullPage: true }); await page.getByRole('button', { name: /^send usdc$/i }).first().click();
await page.getByLabel(/recipient address/i).fill(to);
await page.getByLabel(/amount in usdc/i).fill('5');
await page.getByRole('button', { name: /^review$/i }).click();
await page.screenshot({ path: `${OUT}/send-review.png` });
await page.getByRole('button', { name: /^send 5 usdc$/i }).click();
await page.getByText(/^sent$/i).waitFor({ timeout: 60000 });
await page.screenshot({ path: `${OUT}/send-done.png` });
const cfg = await (await fetch(BASE + '/api/config')).json();
const rpc = await (await fetch(cfg.rpc, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'getTokenAccountsByOwner', params: [to, { mint: cfg.mint }, { encoding: 'jsonParsed', commitment: 'confirmed' }] }) })).json();
console.log('recipient USDC:', rpc.result?.value?.[0]?.account.data.parsed.info.tokenAmount.uiAmountString);
await page.waitForTimeout(1500);
console.log('wallet line:', (await page.locator('body').innerText()).match(/In your wallet: [^\n]+/)?.[0]);
await b.close();
